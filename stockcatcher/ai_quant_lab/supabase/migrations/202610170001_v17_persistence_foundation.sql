-- Atomic commit prevents a crash between paper-fill and event-ledger writes from
-- leaving a fill without its corresponding durable event (or vice versa).
create or replace function public.ai_quant_lab_commit_event(
  p_event jsonb,
  p_outcome jsonb,
  p_trade jsonb default null
) returns table(event_seq bigint, inserted boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_event_id text;
  v_seq bigint;
  v_inserted boolean := false;
  v_payload jsonb;
begin
  v_event_id := p_event ->> 'event_id';
  if v_event_id is null or length(v_event_id) = 0 then
    raise exception 'event_id is required';
  end if;

  insert into public.ai_quant_lab_events
    (event_key, idempotency_key, schema_version, event_type, source, symbol, stock_name, occurred_at, payload)
  values
    (v_event_id, v_event_id, coalesce((p_event ->> 'schema_version')::integer, 1),
     coalesce(p_event ->> 'event_type', 'unknown'), coalesce(p_event ->> 'source', 'ai_quant_lab'),
     nullif(p_event -> 'payload' ->> 'symbol', ''), nullif(p_event -> 'payload' ->> 'stock_name', ''),
     coalesce((p_event ->> 'occurred_at')::timestamptz, now()),
     jsonb_build_object('event', p_event, 'outcome', p_outcome, 'session_id', p_event -> 'session_id'))
  on conflict (idempotency_key) do nothing
  returning ai_quant_lab_events.event_seq into v_seq;
  v_inserted := found;

  -- Even if the event already exists from an earlier partial V16 write, insert the
  -- paper fill once. This repairs legacy partial commits without duplicating a fill.
  if p_trade is not null then
    insert into public.ai_quant_lab_paper_trades
      (trade_key, idempotency_key, session_id, symbol, stock_name, side, quantity, price, fees,
       realized_pnl, strategy, status, executed_at, metadata)
    values
      (p_trade ->> 'trade_key', p_trade ->> 'idempotency_key', nullif(p_trade ->> 'session_id', '')::uuid,
       p_trade ->> 'symbol', p_trade ->> 'stock_name', p_trade ->> 'side',
       (p_trade ->> 'quantity')::integer, (p_trade ->> 'price')::numeric, (p_trade ->> 'fees')::numeric,
       (p_trade ->> 'realized_pnl')::numeric, coalesce(p_trade ->> 'strategy', 'AI_QUANT_LAB_PAPER'),
       coalesce(p_trade ->> 'status', 'FILLED'), coalesce((p_trade ->> 'executed_at')::timestamptz, now()),
       coalesce(p_trade -> 'metadata', '{}'::jsonb))
    on conflict (idempotency_key) do nothing;
  end if;

  if v_seq is null then
    select e.event_seq into v_seq from public.ai_quant_lab_events e where e.idempotency_key = v_event_id;
  end if;
  return query select v_seq, v_inserted;
end;
$$;
revoke all on function public.ai_quant_lab_commit_event(jsonb, jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.ai_quant_lab_commit_event(jsonb, jsonb, jsonb) to service_role;

commit;
