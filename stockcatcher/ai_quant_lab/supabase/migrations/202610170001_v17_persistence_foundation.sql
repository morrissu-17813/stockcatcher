-- AI Quant Lab V17: additive-only persistence foundation.
-- Apply in Supabase SQL Editor after confirming the three V16 tables exist.
-- Does not touch any Tianji 3K production tables.

begin;

-- Existing event ledger: database-owned monotonic sequence and idempotency key.
alter table public.ai_quant_lab_events
  add column if not exists event_seq bigint generated by default as identity,
  add column if not exists idempotency_key text,
  add column if not exists schema_version integer not null default 1;

update public.ai_quant_lab_events
set idempotency_key = event_key
where idempotency_key is null and event_key is not null;

create unique index if not exists uq_ai_quant_lab_events_event_seq
  on public.ai_quant_lab_events(event_seq);
create unique index if not exists uq_ai_quant_lab_events_idempotency
  on public.ai_quant_lab_events(idempotency_key);

alter table public.ai_quant_lab_paper_trades
  add column if not exists idempotency_key text,
  add column if not exists session_id uuid;
update public.ai_quant_lab_paper_trades
set idempotency_key = trade_key
where idempotency_key is null and trade_key is not null;
create unique index if not exists uq_ai_quant_lab_paper_trades_idempotency
  on public.ai_quant_lab_paper_trades(idempotency_key);

create table if not exists public.ai_quant_lab_sessions (
  session_id uuid primary key,
  parent_session_id uuid null references public.ai_quant_lab_sessions(session_id),
