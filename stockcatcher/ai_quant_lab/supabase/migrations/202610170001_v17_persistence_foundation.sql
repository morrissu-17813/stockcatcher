  on public.ai_quant_lab_checkpoints(created_at desc, checkpoint_seq desc);

create table if not exists public.ai_quant_lab_outbox (
  outbox_id uuid primary key,
  session_id uuid null references public.ai_quant_lab_sessions(session_id),
  event_id text not null,
  destination text not null,
  payload jsonb not null,
  status text not null check (status in ('PENDING','SENDING','SENT','RETRY_PENDING','FAILED','UNKNOWN')) default 'PENDING',
  idempotency_key text not null unique,
  attempts integer not null default 0,
  available_at timestamptz not null default now(),
  lease_expires_at timestamptz null,
  last_error text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  sent_at timestamptz null
