  app_version text not null default '17.0.0',
  status text not null check (status in ('STARTING','RUNNING','RECOVERING','DEGRADED','STOPPING','CLOSED','CRASHED')),
  started_at timestamptz not null default now(),
  heartbeat_at timestamptz not null default now(),
  closed_at timestamptz null,
  last_event_seq bigint not null default 0,
  last_checkpoint_id uuid null,
  recovery_summary jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
