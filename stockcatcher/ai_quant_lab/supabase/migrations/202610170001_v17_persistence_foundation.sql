  status text not null check (status in ('PENDING','RUNNING','WAITING_EXTERNAL','RETRY_PENDING','COMPLETED','FAILED','CANCELLED','INTERRUPTED')),
  input_event_ids jsonb not null default '[]'::jsonb,
  result_json jsonb not null default '{}'::jsonb,
  last_completed_step text null,
  attempt_count integer not null default 0,
  lease_owner text null,
  lease_expires_at timestamptz null,
  started_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz null,
  error_code text null,
  error_message text null,
  idempotency_key text not null unique,
  schema_version integer not null default 1
);
create index if not exists ix_ai_quant_lab_agent_runs_recovery
  on public.ai_quant_lab_agent_runs(status, lease_expires_at, updated_at);
create index if not exists ix_ai_quant_lab_agent_runs_prediction
  on public.ai_quant_lab_agent_runs(prediction_id, updated_at desc);

create table if not exists public.ai_quant_lab_checkpoints (
  checkpoint_id uuid primary key,
  session_id uuid not null references public.ai_quant_lab_sessions(session_id),
  checkpoint_seq bigint not null,
  last_event_seq bigint not null default 0,
  state_json jsonb not null,
  state_sha256 text not null,
  schema_version integer not null default 1,
  created_at timestamptz not null default now(),
  is_valid boolean not null default true,
